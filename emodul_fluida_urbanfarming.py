"""---
# BAB 1: Tekanan Hidrostatis
## 🏗️ Konteks: Tandon Air di Atap

Dalam urban farming, air ditampung di **tandon** yang diletakkan di ketinggian tertentu. Semakin tinggi tandon, semakin besar tekanan air yang mendorong aliran ke tanaman.

$$P = \rho \cdot g \cdot h$$

| Simbol | Besaran | Satuan |
|--------|---------|--------|
| $P$ | Tekanan hidrostatis | Pascal (Pa) |
| $\rho$ | Massa jenis fluida | kg/m³ |
| $g$ | Percepatan gravitasi | m/s² |
| $h$ | Ketinggian | meter (m) |
"""

display(HTML('<div class="info">🎮 <b>Simulasi Interaktif:</b> Geser slider untuk melihat pengaruh ketinggian tandon terhadap tekanan air.</div>'))

def simulasi_tekanan(h_tandon, rho):
    g = 9.8
    P = rho * g * h_tandon

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5))
    fig.patch.set_facecolor('#f9fbe7')

    # Gambar sistem tandon
    ax1.set_xlim(0, 10)
    ax1.set_ylim(0, max(h_tandon + 3, 6))
    ax1.set_facecolor('#e8f5e9')
    ax1.set_title('Sistem Tandon Urban Farming', fontsize=13, fontweight='bold')
    ph = h_tandon - 0.5
    ax1.fill_between([2, 7], [ph]*2, [ph+0.3]*2, color='#795548', alpha=0.8)
    tandon = plt.Rectangle((3.5, ph+0.3), 2.5, 1.5, color='#1565c0', alpha=0.7)
    ax1.add_patch(tandon)
    ax1.text(4.75, ph+1.05, 'TANDON', ha='center', va='center', color='white', fontsize=9, fontweight='bold')
    air = plt.Rectangle((3.6, ph+0.4), 2.3, 1.0, color='#29b6f6', alpha=0.6)
    ax1.add_patch(air)
    ax1.fill_between([4.6, 5.1], [0.5]*2, [ph+0.3]*2, color='#78909c', alpha=0.8)
    ax1.fill_between([0, 10], [0]*2, [0.5]*2, color='#6d4c41', alpha=0.7)
    for x in [1.2, 2.5, 7.5, 8.8]:
        ax1.plot([x, x], [0.5, 1.3], color='#2e7d32', lw=2)
        ax1.plot([x-0.3, x+0.3], [1.0, 1.0], color='#43a047', lw=2)
    ax1.annotate('', xy=(6.5, ph+1.0), xytext=(6.5, 0.5), arrowprops=dict(arrowstyle='<->', color='red', lw=2))
    ax1.text(7.2, (ph+1.5)/2, f'h = {h_tandon} m', color='red', fontsize=11, fontweight='bold', va='center')
    ax1.set_xticks([]); ax1.set_ylabel('Ketinggian (m)')

    # Grafik P vs h
    h_range = np.linspace(0, 20, 200)
    P_range = rho * g * h_range / 1000
    ax2.plot(h_range, P_range, color='#1565c0', lw=2.5)
    ax2.axvline(x=h_tandon, color='red', linestyle='--', lw=2, label=f'h = {h_tandon} m')
    ax2.axhline(y=P/1000, color='green', linestyle='--', lw=2, label=f'P = {P/1000:.1f} kPa')
    ax2.scatter([h_tandon], [P/1000], color='red', s=100, zorder=5)
    ax2.fill_between(h_range, P_range, alpha=0.1, color='#1565c0')
    ax2.set_xlabel('Ketinggian tandon (m)', fontsize=11)
    ax2.set_ylabel('Tekanan hidrostatis (kPa)', fontsize=11)
    ax2.set_title('Grafik P vs h', fontsize=13, fontweight='bold')
